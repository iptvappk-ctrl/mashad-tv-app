export async function GET() {
  // Group by category
  const grouped = {
    arabic: PROVIDERS_DATABASE.filter((p) => p.category === "arabic"),
    turkish: PROVIDERS_DATABASE.filter((p) => p.category === "turkish"),
    anime: PROVIDERS_DATABASE.filter((p) => p.category === "anime"),
    foreign: PROVIDERS_DATABASE.filter((p) => p.category === "foreign"),
    mixed: PROVIDERS_DATABASE.filter((p) => p.category === "mixed"),
  };

  return NextResponse.json({
    success: true,
    total: PROVIDERS_DATABASE.length,
    active: PROVIDERS_DATABASE.filter((p) => p.status === "active").length,
    beta: PROVIDERS_DATABASE.filter((p) => p.status === "beta").length,
    providers: PROVIDERS_DATABASE,
    grouped,
    categories: {
      arabic: grouped.arabic.length,
      turkish: grouped.turkish.length,
      anime: grouped.anime.length,
      foreign: grouped.foreign.length,
      mixed: grouped.mixed.length,
    },
    supportedSlugs: [
      "movies", "series", "arabic_movies", "arabic_series",
      "turkish_series", "turkish_movies", "anime", "anime_dubbed",
      "anime_subbed", "anime_movie", "foreign_movies", "foreign_series",
      "ramadan",
    ],
  });
}
